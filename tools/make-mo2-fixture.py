"""Builds a Mod Organizer 2 install: the game folder holds almost nothing, the mods live in an MO2 instance.

    python tools/make-mo2-fixture.py <outdir>
    set CRASHDOCTOR_TEST_ROOT=<outdir>\\mo2
    CrashDoctor.exe --json out.json --game <outdir>\\mo2\\game

This is what lynsis's machine looks like from outside (Nexus, Sep 2026): with MO2 the mods, and once the game has
closed even the frameworks and their logs, are not in the game folder at all. Crash Doctor has to find the instance
and read the merge MO2 would make. Everything below is built to exercise one part of that (ModOrganizer.cs):

- a GLOBAL instance (LocalAppData\\ModOrganizer\\Cyberpunk 2077\\ModOrganizer.ini, which CRASHDOCTOR_TEST_ROOT
  redirects) whose base_directory points elsewhere, gamePath written the way Qt writes it (@ByteArray, doubled
  backslashes), and a second instance for another game that must be ignored
- profile "Default" with modlist.txt in MO2's order (first line = highest priority), a separator, an unmanaged DLC
  line, one disabled mod and one enabled mod whose folder does not exist (rule Mo2EnabledModsMissing)
- RED4ext installed the Root Builder way (Root\\red4ext\\..., Root\\bin\\x64\\winmm.dll); Cyber Engine Tweaks and
  ArchiveXL installed at the data root; one mod with its .archive loose at the top of its folder
- "Better Loot Patch" ships the same BetterLoot.reds as "Better Loot" and sits higher in the list, so Better Loot's
  copy is hidden from the game (rule Mo2HiddenCode); a .mohidden file that must not count
- meta.ini with a Nexus id and version, so the mods table and "Open on Nexus" work
- three sessions whose RED4ext, ArchiveXL and CET logs exist ONLY in MO2's overwrite folder, all quit normally

Expected: manager "Mod Organizer 2", 8 mods (7 enabled), 3 clean sessions, RED4ext / CET / ArchiveXL found, two
archives counted, the two MO2 rules in Health and nothing else that is not info.
"""
import io, os, sys, shutil, datetime

ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
fx = os.path.join(ROOT, "mo2")
if os.path.isdir(fx):
    shutil.rmtree(fx)


def W(path, text="", mode="w"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if mode == "wb": io.open(path, "wb").write(text)
    else: io.open(path, "w", encoding="utf-8", newline="\r\n").write(text)


game = os.path.join(fx, "game")
W(os.path.join(game, "bin", "x64", "Cyberpunk2077.exe"), "not a real executable\n")
os.makedirs(os.path.join(fx, "AppData", "CrashDoctor"), exist_ok=True)
os.makedirs(os.path.join(fx, "LocalAppData", "REDEngine", "ReportQueue"), exist_ok=True)

base = os.path.join(fx, "Modding", "MO2 Cyberpunk")      # the instance's files live away from its ini
mods = os.path.join(base, "mods")
over = os.path.join(base, "overwrite")
prof = os.path.join(base, "profiles", "Default")


def qt_bytes(p):
    return "@ByteArray(" + p.replace("\\", "\\\\") + ")"


inst = os.path.join(fx, "LocalAppData", "ModOrganizer", "Cyberpunk 2077")
W(os.path.join(inst, "ModOrganizer.ini"),
  "[General]\ngameName=Cyberpunk 2077\nselected_profile=@ByteArray(Default)\ngamePath=" + qt_bytes(game) + "\n"
  "version=2.5.2\nfirst_start=false\n\n[Settings]\nbase_directory=" + base.replace("\\", "/") + "\n"
  "mod_directory=%BASE_DIR%/mods\n")
# another game's instance: must not be read
W(os.path.join(fx, "LocalAppData", "ModOrganizer", "Skyrim Special Edition", "ModOrganizer.ini"),
  "[General]\ngameName=Skyrim Special Edition\ngamePath=@ByteArray(C:\\\\Games\\\\Skyrim)\nselected_profile=@ByteArray(Default)\n")
os.makedirs(os.path.join(fx, "LocalAppData", "ModOrganizer", "Skyrim Special Edition", "mods"), exist_ok=True)

# modlist.txt: highest priority first
W(os.path.join(prof, "modlist.txt"), "\n".join([
    "# This file was automatically generated by Mod Organizer.",
    "+Missing Mod",
    "+Better Loot Patch",
    "+Better Loot",
    "-Disabled Mod",
    "+Gameplay_separator",
    "+Loose Archive Mod",
    "+ArchiveXL",
    "+Cyber Engine Tweaks",
    "+RED4ext",
    "*DLC: Phantom Liberty",
]) + "\n")
W(os.path.join(prof, "settings.ini"), "[General]\nLocalSaves=false\n")


def meta(name, modid, version):
    W(os.path.join(mods, name, "meta.ini"), "[General]\ngameName=cyberpunk2077\nmodid=%d\nversion=%s\ninstallationFile=%s.zip\n" % (modid, version, name))


W(os.path.join(mods, "RED4ext", "Root", "red4ext", "RED4ext.dll"), "dll")
W(os.path.join(mods, "RED4ext", "Root", "bin", "x64", "winmm.dll"), "dll")
meta("RED4ext", 2380, "1.30.0")
W(os.path.join(mods, "Cyber Engine Tweaks", "bin", "x64", "plugins", "cyber_engine_tweaks.asi"), "asi")
W(os.path.join(mods, "Cyber Engine Tweaks", "bin", "x64", "plugins", "cyber_engine_tweaks", "fonts", "readme.txt"), "x")
meta("Cyber Engine Tweaks", 107, "1.37.1")
W(os.path.join(mods, "ArchiveXL", "red4ext", "plugins", "ArchiveXL", "ArchiveXL.dll"), "dll")
meta("ArchiveXL", 4198, "1.27.2")
W(os.path.join(mods, "Loose Archive Mod", "loose_hair.archive"), b"\x00" * 300000, "wb")
meta("Loose Archive Mod", 9999, "0.9")
W(os.path.join(mods, "Better Loot", "archive", "pc", "mod", "betterloot.archive"), b"\x00" * 200000, "wb")
W(os.path.join(mods, "Better Loot", "r6", "scripts", "BetterLoot", "BetterLoot.reds"), "// Better Loot 2.1\n")
W(os.path.join(mods, "Better Loot", "r6", "scripts", "BetterLoot", "Old.reds.mohidden"), "// hidden by the user in MO2\n")
meta("Better Loot", 1234, "2.1")
W(os.path.join(mods, "Better Loot Patch", "r6", "scripts", "BetterLoot", "BetterLoot.reds"), "// patched copy\n")
meta("Better Loot Patch", 1235, "1.0")
W(os.path.join(mods, "Disabled Mod", "archive", "pc", "mod", "disabled.archive"), b"\x00" * 4096, "wb")
os.makedirs(os.path.join(mods, "Gameplay_separator"), exist_ok=True)
W(os.path.join(mods, "Gameplay_separator", "meta.ini"), "[General]\n")

# three clean sessions, logged where MO2 puts files the game creates: the overwrite folder
NOW = datetime.datetime.now().replace(microsecond=0)
for day, minutes in ((3, 95), (2, 130), (1, 64)):
    start = NOW - datetime.timedelta(days=day, hours=2)
    end = start + datetime.timedelta(minutes=minutes)
    t = lambda d, ms=0: (start + datetime.timedelta(seconds=d)).strftime("%Y-%m-%d %H:%M:%S") + ".%03d" % ms
    L = ["[%s] [info    ] [  4120] [RED4ext] RED4ext (v1.30.0) is initializing..." % t(0, 101),
         "[%s] [info    ] [  4120] [RED4ext] Product version: 2.31" % t(0, 102),
         "[%s] [info    ] [  4120] [RED4ext] File version: 3.0.80.51928" % t(0, 103),
         "[%s] [info    ] [  4120] [RED4ext] Loading plugins..." % t(1, 400),
         "[%s] [info    ] [  4120] [RED4ext] ArchiveXL (version: 1.27.2, author(s): psiberx) has been loaded" % t(2, 0),
         "[%s] [info    ] [  4120] [RED4ext] 1 plugin(s) loaded" % t(6, 0),
         "[%s] [info    ] [  4120] [RED4ext] RED4ext has been started" % t(6, 200),
         "[%s] [info    ] [  4120] [RED4ext] RED4ext has been shut down" % (end.strftime("%Y-%m-%d %H:%M:%S") + ".880")]
    W(os.path.join(over, "red4ext", "logs", "red4ext-%s.log" % start.strftime("%Y-%m-%d-%H-%M-%S")), "\n".join(L) + "\n")
    W(os.path.join(over, "red4ext", "plugins", "ArchiveXL", "ArchiveXL-%s.log" % start.strftime("%Y-%m-%d-%H-%M-%S")),
      "[%s] [4120] [info] ArchiveXL 1.27.2 initialized.\n" % t(3, 0))
last = NOW - datetime.timedelta(days=1, hours=2)
W(os.path.join(over, "bin", "x64", "plugins", "cyber_engine_tweaks", "cyber_engine_tweaks.log"),
  "[%s UTC-07:00] [info] [Options] [9548] CET version v1.37.1 [HEAD]\n[%s UTC-07:00] [info] [Options] [9548] Game version 3.0.80.51928\n"
  % (last.strftime("%Y-%m-%d %H:%M:%S"), last.strftime("%Y-%m-%d %H:%M:%S")))
print("built mo2      ->", fx)
